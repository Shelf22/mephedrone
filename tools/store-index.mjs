// Builds store/index.json (for hosting, e.g. on GitHub) and the built-in offline catalog from store/plugins/*.
// Every entry carries the SHA-256 of its code; the client refuses code that doesn't match.
import { createHash } from "crypto";
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "store/plugins");
const PERMS = new Set(["commands", "messages.read", "messages.send", "messages.transform", "notify", "style", "network"]);
const entries = [];
for (const id of readdirSync(dir).sort()) {
    const manifest = JSON.parse(readFileSync(join(dir, id, "manifest.json"), "utf8"));
    const code = readFileSync(join(dir, id, "plugin.js"), "utf8");
    if (/\bimport\b/.test(code)) throw new Error(`${id}: store plugins may not use "import" (the client refuses to run them)`);
    if (manifest.id !== id) throw new Error(`${id}: manifest id mismatch`);
    for (const p of manifest.permissions ?? []) if (!PERMS.has(p)) throw new Error(`${id}: unknown permission ${p}`);
    if (manifest.permissions?.includes("network") && !manifest.network?.length) throw new Error(`${id}: network permission needs a domain list`);
    const sha256 = createHash("sha256").update(code).digest("hex");
    entries.push({ manifest, code, sha256, path: `plugins/${id}/plugin.js` });
}
const index = { name: "[MEPHEDRONE] Store", updated: new Date().toISOString().slice(0, 10), plugins: entries.map(e => ({ ...e.manifest, code: e.path, sha256: e.sha256 })) };
writeFileSync(join(root, "store/index.json"), JSON.stringify(index, null, 2) + "\n");
writeFileSync(join(root, "src/plugins/mephStore/builtinCatalog.ts"),
    "/*\n * Vencord, a Discord client mod\n * Copyright (c) 2026 Vendicated and contributors\n * SPDX-License-Identifier: GPL-3.0-or-later\n */\n\n" +
    "// GENERATED by tools/store-index.mjs from store/plugins. Do not edit.\n\n" +
    "import type { CatalogEntry } from \"./types\";\n\n" +
    `export const BUILTIN: CatalogEntry[] = ${JSON.stringify(entries.map(e => ({ ...e.manifest, sha256: e.sha256, codeText: e.code })), null, 4)};\n`);
console.log(`${entries.length} plugins indexed`);
